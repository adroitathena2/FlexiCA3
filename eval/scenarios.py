SCENARIOS_BY_NAME: dict[str, Scenario] = {s.name: s for s in ALL_SCENARIOS}


def get_scenario(name: str) -> Scenario:
    """Look a scenario up by name with a message listing what does exist."""
    try:
        return SCENARIOS_BY_NAME[name]
    except KeyError as exc:
        raise KeyError(
            f"unknown scenario {name!r}; known scenarios: {sorted(SCENARIOS_BY_NAME)}"
        ) from exc


def _self_check(scenarios: Iterable[Scenario] = ALL_SCENARIOS) -> None:
    """Assert the fixtures say what they claim to say.

    Called from tests, not at import time: an expensive invariant check must not
    slow down ``import eval`` for a caller who only wants one scenario.

    Verifies the two provable claims in the spec — S1's exclusivity really is
    over cap, and S2's lead really is negative-EV — so a later edit to a
    literal cannot quietly remove the conflict the scenario exists to create.
    """
    for s in scenarios:
        for offer in s.seed_data.offers:
            offer.violations(s.policy)  # raises nothing; assertion is below

    s1 = get_scenario("S1_exclusivity_conflict")
    seeded = s1.offer_for("Helio Fintech")
    assert seeded.exclusivity_days > s1.policy.max_exclusivity_days, (
        "S1 must breach the exclusivity cap or it forces no conflict")
    assert seeded.attendee_data_clause and not s1.policy.allow_attendee_data_transfer, (
        "S1 must breach the data-transfer ban or it forces no conflict")
    assert any(c.parties == (AgentId.A2_PRICING, AgentId.A5_COMPLIANCE)
               for c in s1.expected_conflicts), "S1 must expect an A2-vs-A5 dispute"

    s2 = get_scenario("S2_low_ev_lead")
    cold = s2.brand("Fjordline Logistics")
    assert s2.seed_data.is_bad_bet(cold), (
        f"S2 lead EV {s2.seed_data.lead_ev(cold)} is not below outreach cost "
        f"{s2.seed_data.outreach_cost_inr}; the scenario would force no conflict")
    assert any(c.parties == (AgentId.A3_OUTREACH, AgentId.A6_AUDIT)
               for c in s2.expected_conflicts), "S2 must expect an A3-vs-A6 dispute"

    s5 = get_scenario("S5_vision_gap")
    assert s5.seed_data.missing_evidence, "S5 must genuinely lack evidence"
    assert all(o.deliverables_evidence_url is None for o in s5.seed_data.offers), (
        "S5's offers must carry no fulfilment evidence URL")


