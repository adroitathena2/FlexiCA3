"""Deterministic, seeded evaluation fixtures.

Why this module exists
----------------------
An ablation can only prove a claim about *adaptivity* if the inputs it replays
are fixed and every condition sees byte-identical inputs. So the inputs live here
as data, not as code paths inside an agent.

Two hard rules, both of which exist because the previous version of this project
shipped a hand-written trace with invented numbers:

1. **Every seeded artefact carries ``source="fixture"``.** ``BrandLead`` has a
   ``source`` field for exactly this; seeded offers carry it on the enclosing
   ``SeedOffer`` because ``core.schemas.Offer`` is a frozen contract and adding a
   field to it would break every module being written in parallel.
2. **Every brand in a fixture is synthetic.** A fixture that named a real company
   while inventing its footfall or budget would be fabricated evidence about a
   real business. The names here are invented; the ``notes`` on each scenario say
   so, and the provenance block in ``eval/report.py`` repeats it.

Determinism
-----------
Every random draw in the harness is derived from
``random.Random(f"{scenario_name}:{seed}")``. Two consequences:

* A ``(scenario, seed)`` pair yields identical runs regardless of iteration order
  or how many other scenarios ran first, so a report can be regenerated from its
  printed seed list and must match.
* The default seed is :data:`DEFAULT_SEED` (``20260210``, the date of the first
  recorded run of this project). Change it and every number in the report changes;
  it is printed in the provenance block of every report so that is never ambiguous.

Ground-truth labels
-------------------
``ReplyProbe.expected_intent`` / ``expected_agent`` are *hand-specified judgement*,
not model output. Each carries a ``rationale`` saying why, and they follow the
ordering frozen in ``core.protocols.classify_intent_fallback`` (refusal and
pushback are tested **before** assent) and the rationale documented on
``core.schemas.Intent``. Labelling a probe by calling the same fallback function
the conditions are being compared against would make the comparison circular, so
the labels are stated independently and the routing policy is applied separately.
"""
