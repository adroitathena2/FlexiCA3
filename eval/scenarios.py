#: Documented, fixed base seed. See the module docstring for why it is fixed.
DEFAULT_SEED: int = 20260210

#: The literal written into every seeded artefact's provenance field.
FIXTURE_SOURCE: str = "fixture"

#: Repeated in ``eval/report.py`` provenance so a reader never mistakes a fixture
#: brand for a researched one.
